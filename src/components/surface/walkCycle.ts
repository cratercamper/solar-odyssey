const N = T.hip.length
/** 一周（2 歩）で進む距離（m）。参考の歩きは 1.2 m/s で 1.4 秒に 1.7 m */
export const CYCLE_M = 1.7
/** 立った姿勢（平均）：歩く大きさ amp が 0 のときは、ここへ寄る */
const mean = (a: number[]) => a.reduce((s, v) => s + v, 0) / a.length

export type LegAt = { hip: number; knee: number; foot: number; arm: number; elbow: number; contact: boolean }

const at = (a: number[], p: number) => {
  const x = (((p % 1) + 1) % 1) * N
  const i = Math.floor(x)
  const f = x - i
  return a[i] * (1 - f) + a[(i + 1) % N] * f
}

/** 周期 p（0〜1）の、片足の角度。amp（0〜1）で動きの大きさを変える（0 はまっすぐ立つ） */
export function legAt(p: number, amp = 1): LegAt {
  const c = at(T.contact, p) > 0.5
  return {
    hip: at(T.hip, p) * amp,
    // ひざは立ったときでも少し曲がるので、0 からの増えぶんを小さくする
    knee: 0.08 + (at(T.knee, p) - 0.08) * amp,
    foot: at(T.foot, p) * amp,
    arm: (at(T.arm, p) - mean(T.arm)) * amp,
    elbow: -0.15 + (at(T.elbow, p) + 0.15) * amp,
    contact: c,
  }
}
